import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');
const SRC_CORE = path.join(ROOT_DIR, 'core');
const DEST_CORE = path.join(ROOT_DIR, 'apps', 'extension', 'core');

function copyDirRecursive(src, dest) {
  if (!fs.existsSync(dest)) {
    fs.mkdirSync(dest, { recursive: true });
  }

  const entries = fs.readdirSync(src, { withFileTypes: true });
  for (const entry of entries) {
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);

    if (entry.isDirectory()) {
      copyDirRecursive(srcPath, destPath);
    } else {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

console.log('--- Syncing ZunDeck Core to Extension Bundle ---');
copyDirRecursive(SRC_CORE, DEST_CORE);
console.log(`✓ Synchronized core/ to apps/extension/core/ successfully.`);
