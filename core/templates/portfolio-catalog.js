export function getTemplateById(templateId) {
  return PORTFOLIO_CATALOG.find((t) => t.id === templateId) || PORTFOLIO_CATALOG[0];
}

export function getTemplatesByCategory(category) {
  if (!category || category === 'all') return PORTFOLIO_CATALOG;
  return PORTFOLIO_CATALOG.filter((t) => t.category === category);
}
